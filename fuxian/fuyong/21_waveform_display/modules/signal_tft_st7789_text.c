static int GlyphIndex(char symbol)
{
    if ((symbol >= '0') && (symbol <= '9')) return symbol - '0';
    if ((symbol >= 'A') && (symbol <= 'Z')) return 10 + symbol - 'A';
    return -1;
}

signal_result_t SignalTFTST7789Text_DrawChar(tft_st7789_t *tft,
    int32_t x, int32_t y, char symbol, uint8_t scale,
    uint16_t foreground, uint16_t background)
{
    int index = GlyphIndex(symbol);
    uint8_t row;
    uint8_t column;
    if ((index < 0) || (scale == 0U)) return SIGNAL_RESULT_INVALID_ARGUMENT;
    if (TFT_ST7789_FillRect(tft, x, y, 5 * scale, 7 * scale, background) !=
        SIGNAL_RESULT_OK) return SIGNAL_RESULT_HARDWARE_ERROR;
    for (row = 0U; row < 7U; ++row) {
        for (column = 0U; column < 5U; ++column) {
            if ((g_glyphs[index][row] & (uint8_t)(1U << (4U - column))) != 0U) {
                if (TFT_ST7789_FillRect(tft, x + column * scale,
                        y + row * scale, scale, scale, foreground) !=
                    SIGNAL_RESULT_OK) return SIGNAL_RESULT_HARDWARE_ERROR;
            }
        }
    }
    return SIGNAL_RESULT_OK;
}

signal_result_t SignalTFTST7789Text_DrawString(tft_st7789_t *tft,
    int32_t x, int32_t y, const char *text, uint8_t scale,
    uint16_t foreground, uint16_t background)
{
    int32_t cursor = x;
    size_t index;
    if ((text == NULL) || (scale == 0U)) return SIGNAL_RESULT_INVALID_ARGUMENT;
    for (index = 0U; text[index] != '\0'; ++index) {
        if (text[index] == ' ') {
            if (TFT_ST7789_FillRect(tft, cursor, y, 6 * scale, 7 * scale,
                    background) != SIGNAL_RESULT_OK) return SIGNAL_RESULT_HARDWARE_ERROR;
        } else if (SignalTFTST7789Text_DrawChar(tft, cursor, y, text[index],
                       scale, foreground, background) != SIGNAL_RESULT_OK) {
            return SIGNAL_RESULT_HARDWARE_ERROR;
        }
        cursor += 6 * scale;
    }
    return SIGNAL_RESULT_OK;
}

signal_result_t SignalTFTST7789Text_DrawUint(tft_st7789_t *tft,
    int32_t x, int32_t y, uint32_t value, uint8_t digits, uint8_t scale,
    uint16_t foreground, uint16_t background)
{
    char text[10];
    uint8_t i;
    if ((digits == 0U) || (digits >= sizeof(text)) || (scale == 0U)) {
        return SIGNAL_RESULT_INVALID_ARGUMENT;
    }
    for (i = 0U; i < digits; ++i) {
        text[digits - 1U - i] = (char)('0' + (value % 10U));
        value /= 10U;
    }
    text[digits] = '\0';
    return SignalTFTST7789Text_DrawString(tft, x, y, text, scale,
        foreground, background);
}

signal_module_status_t SignalTFTST7789Text_GetModuleStatus(void)
{
    return MODULE_STATUS_BUILD_VERIFIED;
}
